#!/usr/bin/env python3
"""Builds js/data/timezones.js: every airport's local time (UTC offsets in winter and summer, and when summer time
starts and ends) from the time zone of the nearest town in the same country.

Source (download into tools/cache/ first):
  https://download.geonames.org/export/dump/cities1000.zip  (unzipped: cities1000.txt, CC BY 4.0, geonames.org)
The offsets come from Python's time zone database (zoneinfo), for the year 2025.

Usage: python3 tools/build_timezones.py [cache dir]
"""
import datetime as dt
import json
import math
import os
import re
import sys
import zoneinfo

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'tools', 'cache')
YEAR = 2025


def airports():
    out = []
    # hand-made ones: { code: 'BRN', ..., country: 'CH', lat: 46.914, lon: 7.499, ... }
    src = open(os.path.join(ROOT, 'js', 'data', 'airports.js'), encoding='utf-8').read()
    for m in re.finditer(r"code: '(\w+)'.*?country: '(\w*)', lat: (-?[\d.]+), lon: (-?[\d.]+)", src):
        out.append((m[1], m[2], float(m[3]), float(m[4])))
    for line in open(os.path.join(ROOT, 'js', 'data', 'airports-more.js'), encoding='utf-8'):
        line = line.strip().rstrip(',')
        if line.startswith('["'):
            r = json.loads(line)
            out.append((r[0], r[3], r[4], r[5]))
    return out


def towns():
    by = {}
    for line in open(os.path.join(CACHE, 'cities1000.txt'), encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) < 18 or not f[17]:
            continue
        lat, lon = float(f[4]), float(f[5])
        by.setdefault(f[8], {}).setdefault((math.floor(lat), math.floor(lon)), []).append((lat, lon, f[17]))
    return by


def nearest(grid, lat, lon):
    best, bd = None, 1e18
    for ring in range(0, 40):
        for i in range(-ring, ring + 1):
            for j in range(-ring, ring + 1):
                if max(abs(i), abs(j)) != ring:
                    continue
                for (a, b, tz) in grid.get((math.floor(lat) + i, math.floor(lon) + j), ()):
                    d = (a - lat) ** 2 + ((b - lon) * math.cos(math.radians(lat))) ** 2
                    if d < bd:
                        best, bd = tz, d
        if best and ring >= 1:
            return best
    return best


def zone(name):
    z = zoneinfo.ZoneInfo(name)
    off = lambda d: int(d.replace(tzinfo=z).utcoffset().total_seconds() // 60)
    jan, jul = off(dt.datetime(YEAR, 1, 15, 12)), off(dt.datetime(YEAR, 7, 15, 12))
    if jan == jul:
        return (jan // 15,)
    # the days of the year (0 = 1 January) on which the clocks change
    changes = []
    for d in range(1, 366):
        a, b = dt.datetime(YEAR, 1, 1) + dt.timedelta(days=d - 1, hours=12), dt.datetime(YEAR, 1, 1) + dt.timedelta(days=d, hours=12)
        if off(a) != off(b):
            changes.append(d)
    return (jan // 15, jul // 15, *changes[:2])


def main():
    by = towns()
    world = {}
    for grid in by.values():
        for k, v in grid.items():
            world.setdefault(k, []).extend(v)
    groups = {}
    for code, country, lat, lon in airports():
        tz = nearest(by.get(country, {}), lat, lon) or nearest(world, lat, lon)
        if not tz:
            continue
        key = ','.join(map(str, zone(tz)))
        groups.setdefault(key, []).append(code)
    path = os.path.join(ROOT, 'js', 'data', 'timezones.js')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_timezones.py from GeoNames cities1000 (CC BY 4.0, geonames.org) and the\n')
        f.write('// time zone database. Do not edit by hand.\n')
        f.write('// "winter,summer,starts,ends": UTC offsets in quarter hours, summer time from day `starts` to `ends` of the\n')
        f.write('// year (0 = 1 January; ends < starts in the south). One number: no summer time. Then the airports.\n')
        f.write('FG.data.timezones = {\n')
        for key in sorted(groups, key=lambda k: [int(x) for x in k.split(',')]):
            f.write(f'  "{key}": "{" ".join(sorted(set(groups[key])))}",\n')
        f.write('};\n')
    print(f'{sum(len(set(v)) for v in groups.values())} airports in {len(groups)} groups -> {path}')


main()
